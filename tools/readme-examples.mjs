function text(locale, english, korean) {
  return locale === "ko-KR" ? korean : english;
}

function claim(locale, english, korean, evidence, basis = "code") {
  return {
    basis,
    evidence,
    text: text(locale, english, korean),
  };
}

function reference(sourceId, startLine, endLine = startLine) {
  return { endLine, sourceId, startLine };
}

function sourceReference(snapshot, sourceId, startText, endText = startText) {
  const source = snapshot.sources.find(({ id }) => id === sourceId);
  if (!source) throw new Error(`Unknown README example source: ${sourceId}`);
  const lines = source.text.split("\n");
  const startIndex = lines.findIndex((line) => line.includes(startText));
  const endIndex = lines.findIndex((line, index) => (
    index >= startIndex && line.includes(endText)
  ));
  if (startIndex < 0 || endIndex < 0) {
    throw new Error(`README example evidence text is missing from ${sourceId}`);
  }
  return reference(sourceId, startIndex + 1, endIndex + 1);
}

