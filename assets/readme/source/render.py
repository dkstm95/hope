class Face:
    """One font with glyph outlines, advances, and GPOS pair kerning."""

    def __init__(self, key: str, path: Path):
        self.key = key
        self.font = TTFont(path)
        self.cmap = self.font.getBestCmap()
        self.glyph_set = self.font.getGlyphSet()
        self.hmtx = self.font["hmtx"]
        self.upm = self.font["head"].unitsPerEm
        self.paths: dict[str, str] = {}
        self.pairs, self.classes = self._load_kerning()

    def _load_kerning(self):
        pairs: dict[tuple[str, str], int] = {}
        classes = []
        if "GPOS" not in self.font:
            return pairs, classes
        gpos = self.font["GPOS"].table
        indices: set[int] = set()
        for record in gpos.FeatureList.FeatureRecord:
            if record.FeatureTag == "kern":
                indices.update(record.Feature.LookupListIndex)
        for index in sorted(indices):
            for subtable in gpos.LookupList.Lookup[index].SubTable:
                if subtable.LookupType == 9:
                    subtable = subtable.ExtSubTable
                if subtable.LookupType != 2:
                    continue
                if subtable.Format == 1:
                    for first, pair_set in zip(subtable.Coverage.glyphs, subtable.PairSet):
                        for record in pair_set.PairValueRecord:
                            value = getattr(record.Value1, "XAdvance", 0) or 0
                            pairs.setdefault((first, record.SecondGlyph), value)
                elif subtable.Format == 2:
                    classes.append((
                        set(subtable.Coverage.glyphs),
                        subtable.ClassDef1.classDefs,
                        subtable.ClassDef2.classDefs,
                        subtable.Class1Record,
                    ))
        return pairs, classes

    def kern(self, first: str, second: str) -> int:
        if (first, second) in self.pairs:
            return self.pairs[(first, second)]
        for coverage, class1, class2, records in self.classes:
            if first not in coverage:
                continue
            record = records[class1.get(first, 0)].Class2Record[class2.get(second, 0)]
            value = getattr(record.Value1, "XAdvance", 0) or 0
            if value:
                return value
        return 0

    def glyph(self, char: str) -> str:
        return self.cmap.get(ord(char)) or self.cmap[0x3F]

    def advance(self, name: str) -> int:
        return self.hmtx[name][0]

    def path(self, name: str) -> str:
        if name not in self.paths:
            pen = SVGPathPen(self.glyph_set, ntos=lambda value: str(round(value)))
            self.glyph_set[name].draw(pen)
            self.paths[name] = pen.getCommands()
        return self.paths[name]


