def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    for locale, labels in LABELS.items():
        for theme, colors in THEMES.items():
            for name, scene in SCENES.items():
                title, description = TITLES[locale][name]
                path = OUT / f"hope-{name}-{locale}-{theme}.svg"
                path.write_text(scene(labels, colors).render(title, description), encoding="utf-8")
                written.append(path)
    for name in MARKS:
        path = OUT / f"mark-{name}.svg"
        path.write_text(mark(name), encoding="utf-8")
        written.append(path)
    for path in written:
        print(f"{path.relative_to(ROOT)}  {path.stat().st_size:>7} bytes")


