def glyph_id(face: Face, name: str) -> str:
    return f"{face.key}-{re.sub(r'[^A-Za-z0-9_.-]', '_', name)}"


class Doc:
    """Collects SVG elements and the glyph definitions they use."""

    def __init__(self, width: int, height: int):
        self.width = width
        self.height = height
        self.defs: dict[str, str] = {}
        self.body: list[str] = []

    def layout(self, text: str, face: Face, size: float, tracking: float = 0):
        if HANGUL.search(text):
            tracking = 0
            if face.key == "code":
                face = FACES["medium"]
        scale = size / face.upm
        names = [face.glyph(char) for char in text]
        positions = []
        cursor = 0.0
        for index, name in enumerate(names):
            if index:
                cursor += face.kern(names[index - 1], name)
            positions.append((name, cursor))
            cursor += face.advance(name) + tracking / scale
        return names, positions, cursor * scale

    def wrap(self, text: str, face: Face, size: float, width: float) -> list[str]:
        rows, current = [], ""
        for word in text.split(" "):
            candidate = f"{current} {word}".strip()
            if current and self.measure(candidate, face, size) > width:
                rows.append(current)
                current = word
            else:
                current = candidate
        return rows + [current]

    def measure(self, text: str, face: Face, size: float, tracking: float = 0) -> float:
        return self.layout(text, face, size, tracking)[2]

    def text(self, x: float, y: float, text: str, face: Face, size: float, fill: str,
             anchor: str = "start", tracking: float = 0, opacity: float | None = None) -> float:
        if HANGUL.search(text) and face.key == "code":
            face = FACES["medium"]
        names, positions, width = self.layout(text, face, size, tracking)
        if anchor == "end":
            x -= width
        elif anchor == "middle":
            x -= width / 2
        scale = size / face.upm
        uses = []
        for name, cursor in positions:
            if name in (".notdef", "space") or face.advance(name) and not face.path(name):
                continue
            identifier = glyph_id(face, name)
            self.defs.setdefault(identifier, face.path(name))
            uses.append(f'<use href="#{identifier}" x="{round(cursor)}"/>')
        attributes = f' fill="{fill}"'
        if opacity is not None:
            attributes += f' opacity="{opacity}"'
        self.body.append(
            f'<g transform="translate({fmt(x)} {fmt(y)}) scale({scale:.5f} {-scale:.5f})"{attributes}>'
            + "".join(uses) + "</g>"
        )
        return width

    def raw(self, markup: str) -> None:
        self.body.append(markup)

    def rect(self, x, y, w, h, fill="none", stroke=None, radius=0, width=1, opacity=None):
        attributes = f'x="{fmt(x)}" y="{fmt(y)}" width="{fmt(w)}" height="{fmt(h)}" fill="{fill}"'
        if radius:
            attributes += f' rx="{fmt(radius)}"'
        if stroke:
            attributes += f' stroke="{stroke}" stroke-width="{width}"'
        if opacity is not None:
            attributes += f' opacity="{opacity}"'
        self.body.append(f"<rect {attributes}/>")

    def line(self, x1, y1, x2, y2, stroke, width=1, dash=None, cap=None):
        attributes = f'x1="{fmt(x1)}" y1="{fmt(y1)}" x2="{fmt(x2)}" y2="{fmt(y2)}" stroke="{stroke}" stroke-width="{width}"'
        if dash:
            attributes += f' stroke-dasharray="{dash}"'
        if cap:
            attributes += f' stroke-linecap="{cap}"'
        self.body.append(f"<line {attributes}/>")

    def circle(self, cx, cy, r, fill="none", stroke=None, width=1):
        attributes = f'cx="{fmt(cx)}" cy="{fmt(cy)}" r="{fmt(r)}" fill="{fill}"'
        if stroke:
            attributes += f' stroke="{stroke}" stroke-width="{width}"'
        self.body.append(f"<circle {attributes}/>")

    def render(self, title: str, description: str) -> str:
        defs = "".join(f'<path id="{key}" d="{value}"/>' for key, value in self.defs.items())
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" height="{self.height}" '
            f'viewBox="0 0 {self.width} {self.height}" role="img" aria-labelledby="title desc">'
            f"{GENERATED}"
            f"<title id=\"title\">{escape(title)}</title><desc id=\"desc\">{escape(description)}</desc>"
            f"<defs>{defs}</defs>" + "".join(self.body) + "</svg>\n"
        )


def fmt(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return text if text else "0"


def escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# Drawing helpers shared by the artifact illustrations.


def frame(doc: Doc, T: dict, rail_width: int = 0) -> None:
    doc.rect(0.5, 0.5, doc.width - 1, doc.height - 1, fill=T["panel"], stroke=T["rule"], radius=10)
    if rail_width:
        doc.raw(
            f'<path d="M10.5 0.5 H{rail_width}.5 V{doc.height - 0.5} H10.5 A10 10 0 0 1 0.5 {doc.height - 10.5} '
            f'V10.5 A10 10 0 0 1 10.5 0.5 Z" fill="{T["rail"]}" stroke="{T["rule"]}"/>'
        )


def rail(doc: Doc, T: dict, brand: str, identity: str, index_label: str, entries: list[str],
         current: int, footer: str | None = None, width: int = 200) -> None:
    doc.text(22, 36, brand, FACES["code"], 12, T["accent"], tracking=0.6)
    brand_width = doc.measure(brand, FACES["code"], 12, tracking=0.6)
    doc.text(22 + brand_width + 8, 36, "/", FACES["code"], 12, T["muted"])
    doc.text(22 + brand_width + 20, 36, identity, FACES["code"], 12, T["text"], tracking=0.6)
    doc.line(22, 58, width - 22, 58, T["rule"])
    doc.text(22, 84, index_label, FACES["code"], 9.5, T["muted"], tracking=0.8)
    y = 114
    for number, entry in enumerate(entries, start=1):
        is_current = number == current
        if is_current:
            doc.line(22, y - 15, 22, y + 7, T["accent"], width=2)
        doc.text(36, y, f"{number:02d}", FACES["code"], 10, T["accent"] if is_current else T["muted"])
        for row in entry.split("\n"):
            doc.text(58, y, row, FACES["bold" if is_current else "medium"], 13,
                     T["text"] if is_current else T["muted"])
            y += 18
        y += 14
    if footer:
        doc.line(22, doc.height - 50, width - 22, doc.height - 50, T["rule"])
        doc.text(22, doc.height - 26, footer, FACES["medium"], 11.5, T["muted"])


def section(doc: Doc, T: dict, x: float, y: float, w: float, number: str, title: str) -> None:
    doc.text(x, y, number, FACES["code"], 11.5, T["accent"], tracking=0.4)
    doc.text(x + 34, y, title, FACES["code"], 11.5, T["text"], tracking=1.2)
    doc.line(x, y + 14, x + w, y + 14, T["rule"])


def marker(doc: Doc, T: dict, x: float, y: float, label: str, color: str, filled: bool = False) -> float:
    width = doc.measure(label, FACES["code"], 9, tracking=0.6) + 12
    doc.rect(x, y - 10.5, width, 15, fill=color if filled else "none", stroke=color, radius=3)
    doc.text(x + 6, y, label, FACES["code"], 9, T["panel"] if filled else color, tracking=0.6)
    return width


def evidence(doc: Doc, T: dict, x: float, y: float, numbers: list[int]) -> float:
    start = x
    for number in numbers:
        label = f"[{number}]"
        width = doc.measure(label, FACES["code"], 9.5)
        doc.text(x, y, label, FACES["code"], 9.5, T["link"])
        x += width + 5
    return x - start


def lines(doc: Doc, x: float, y: float, rows: list[str], face: Face, size: float, fill: str,
          leading: float) -> float:
    for row in rows:
        doc.text(x, y, row, face, size, fill)
        y += leading
    return y


