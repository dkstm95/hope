#!/usr/bin/env python3
"""Render the Hope mark, wordmark, icons, and social preview in assets/brand.

The mark is two overlapping circles: pink for the person, blue for the AI.
Where they overlap, the colors mix like two inks on paper (multiply) in light
and like two beams of light (screen) in dark, and one point is cut out of the
overlap: the decision that stays with the person. The wordmark puts the mark
in place of the o in Hope.

    python3 assets/brand/source/render.py

Writes the SVGs, then runs rasterize.mjs (Playwright Chromium) for the PNGs,
including the plugin icons under plugins/hope. Text comes from Hope Sans Bold
through the README generator's text engine, converted to paths.
"""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "assets" / "brand"
SOURCE = OUT / "source"

if "readme_render" in sys.modules:
    readme = sys.modules["readme_render"]
else:
    _spec = importlib.util.spec_from_file_location("readme_render", ROOT / "assets/readme/source/render.py")
    readme = importlib.util.module_from_spec(_spec)
    sys.modules["readme_render"] = readme
    _spec.loader.exec_module(readme)
Doc, FACES, THEMES, fmt = readme.Doc, readme.FACES, readme.THEMES, readme.fmt

GENERATED = "<!-- Generated by assets/brand/source/render.py. Edit that file and run it again. -->"

# Brand inks. The artifact theme has no pink or blue token, so these two are
# the brand's own; neutrals come from the artifact theme through THEMES.
PINK = "#ff4f8b"
BLUE = "#3157ff"
# A lighter tint of BLUE for text on dark backgrounds.
BLUE_ON_DARK = "#8ea2ff"

# Mark geometry on a 64-unit grid.
LEFT, RIGHT, CY, RADIUS, POINT = 25, 39, 32, 15, 3.6
BOX = (LEFT - RADIUS, CY - RADIUS, RIGHT + RADIUS, CY + RADIUS)  # 10 17 54 47


def _rgb(color: str) -> list[int]:
    return [int(color[i:i + 2], 16) for i in (1, 3, 5)]


def blend(theme: str) -> str:
    """The overlap color: multiply in light, screen in dark."""
    a, b = _rgb(PINK), _rgb(BLUE)
    if theme == "light":
        mixed = [x * y / 255 for x, y in zip(a, b)]
    else:
        mixed = [255 - (255 - x) * (255 - y) / 255 for x, y in zip(a, b)]
    return "#" + "".join(f"{round(v):02x}" for v in mixed)


def mark(theme: str, key: str, transform: str = "") -> str:
    """The mark as an SVG group. The point is a hole, so the background shows through."""
    clip, mask = f"{key}-overlap", f"{key}-point"
    group = f' transform="{transform}"' if transform else ""
    return (
        f'<g{group}><defs><clipPath id="{clip}"><circle cx="{LEFT}" cy="{CY}" r="{RADIUS}"/></clipPath>'
        f'<mask id="{mask}" maskUnits="userSpaceOnUse" x="0" y="0" width="64" height="64">'
        f'<rect width="64" height="64" fill="#fff"/><circle cx="32" cy="{CY}" r="{POINT}" fill="#000"/></mask></defs>'
        f'<g mask="url(#{mask})"><circle cx="{LEFT}" cy="{CY}" r="{RADIUS}" fill="{PINK}"/>'
        f'<circle cx="{RIGHT}" cy="{CY}" r="{RADIUS}" fill="{BLUE}"/>'
        f'<circle cx="{RIGHT}" cy="{CY}" r="{RADIUS}" fill="{blend(theme)}" clip-path="url(#{clip})"/></g></g>'
    )


def wordmark(doc: Doc, x: float, baseline: float, size: float, theme: str, key: str = "wordmark") -> float:
    """Draw Hope with the mark as its o. Returns the width."""
    face, tracking, ink = FACES["bold"], -size * 0.024, THEMES[theme]["text"]
    start = x
    x += doc.text(x, baseline, "H", face, size, ink, tracking=tracking)
    x_height = face.font["OS/2"].sxHeight / face.upm * size
    scale = x_height * 1.06 / (2 * RADIUS)  # optical overshoot, like a round glyph
    gap = size * 0.04
    mark_width = (BOX[2] - BOX[0]) * scale
    left = x + gap
    doc.raw(mark(theme, key, f"translate({fmt(left)} {fmt(baseline - x_height / 2)}) "
                             f"scale({scale:.4f}) translate({-BOX[0]} {-CY})"))
    x = left + mark_width + gap
    x += doc.text(x, baseline, "pe", face, size, ink, tracking=tracking)
    return x - start


def svg(width: float, height: float, body: str, title: str, view: str | None = None, defs: str = "") -> str:
    view = view or f"0 0 {fmt(width)} {fmt(height)}"
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{fmt(width)}" height="{fmt(height)}" viewBox="{view}" '
        f'role="img" aria-label="{title}">{GENERATED}<defs>{defs}</defs>{body}</svg>\n'
    )


def icon(theme: str, small: bool = False) -> str:
    """The square app icon. Small sizes enlarge the mark so the point survives at 16 to 32 px."""
    tile = THEMES[theme]["panel"] if theme == "dark" else "#ffffff"
    scale = 1.32 if small else 1.12
    body = (f'<rect width="64" height="64" rx="15" fill="{tile}"/>'
            + mark(theme, f"icon-{theme}", f"translate(32 32) scale({scale}) translate(-32 -32)"))
    return svg(64, 64, body, "Hope")


def bare_mark(theme: str) -> str:
    w, h = BOX[2] - BOX[0], BOX[3] - BOX[1]
    return svg(w * 4, h * 4, mark(theme, f"mark-{theme}"), "Hope", view=f"{BOX[0]} {BOX[1]} {w} {h}")


def doc_svg(doc: Doc, title: str, background: str | None = None) -> str:
    defs = "".join(f'<path id="{k}" d="{v}"/>' for k, v in doc.defs.items())
    body = (f'<rect width="{doc.width}" height="{doc.height}" fill="{background}"/>' if background else "") + "".join(doc.body)
    return svg(doc.width, doc.height, body, title, defs=defs)


def wordmark_svg(theme: str) -> str:
    probe = Doc(1, 1)
    size, pad = 96, 4
    width = wordmark(probe, 0, 0, size, theme)
    doc = Doc(round(width + 2 * pad), 120)
    wordmark(doc, pad, 92, size, theme)
    return doc_svg(doc, "Hope")


def social() -> str:
    """The 1280 x 640 GitHub repository card, light only."""
    T = THEMES["light"]
    doc = Doc(1280, 640)
    # A large, faint print of the mark bleeding off the right edge, as on a riso poster.
    doc.raw(f'<g opacity=".14">{mark("light", "social-print", "translate(1150 300) scale(12) translate(-32 -32)")}</g>')
    wordmark(doc, 96, 300, 168, "light", key="social-wordmark")
    doc.text(100, 396, "See more. Understand more. Decide more.", FACES["medium"], 36, T["text"], tracking=-0.5)
    doc.text(100, 446, "A Claude Code and Codex plugin that keeps your judgment", FACES["medium"], 25, T["muted"])
    doc.text(100, 482, "and agency while AI does more of the work.", FACES["medium"], 25, T["muted"])
    doc.text(100, 568, "github.com/dkstm95/hope", FACES["code"], 22, T["muted"])
    return doc_svg(doc, "Hope: see more, understand more, decide more.", background="#fafafa")


def main() -> None:
    files = {
        "hope-mark-light.svg": bare_mark("light"),
        "hope-mark-dark.svg": bare_mark("dark"),
        "hope-wordmark-light.svg": wordmark_svg("light"),
        "hope-wordmark-dark.svg": wordmark_svg("dark"),
        "hope-icon.svg": icon("light"),
        "hope-icon-dark.svg": icon("dark"),
        "hope-icon-small.svg": icon("light", small=True),
        "hope-social-preview.svg": social(),
    }
    for name, text in files.items():
        path = OUT / name
        path.write_text(text, encoding="utf-8")
        print(f"{path.relative_to(ROOT)}  {path.stat().st_size:>7} bytes")
    subprocess.run(["node", str(SOURCE / "rasterize.mjs")], check=True, cwd=ROOT)


if __name__ == "__main__":
    main()
